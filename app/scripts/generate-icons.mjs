// Writes src/app/core/icons.ts: every ionicon the app uses. Icons of recognised
// components come from the agent's catalog, so a new catalog entry never shows
// a blank slot. Run after changing the catalog or using a new icon in the UI:
//   node scripts/generate-icons.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
// The catalog and every module (core checks and integrations live in folders under modules/).
const modules = readdirSync(join(root, '../agent/src/modules'), { recursive: true })
  .filter((f) => f.endsWith('.ts') && !f.endsWith('.spec.ts'))
  .map((f) => `../agent/src/modules/${f}`);
const fromAgent = ['../agent/src/discovery/catalog.ts', ...modules].flatMap((f) =>
  [...readFileSync(join(root, f), 'utf8').matchAll(/icon(?::| =) '([a-z-]+)'/g)].map((m) => m[1]),
);

// Icons the app's own templates use by name.
const ui = `add-outline alert-circle checkmark-circle cloud-offline-outline document-text-outline refresh-outline
reload-outline save-outline settings-outline sync-outline trash-outline warning chevron-down chevron-forward
chevron-back open-outline search-outline close copy-outline notifications-outline notifications-off-outline heart-outline time-outline
qr-code-outline link-outline hardware-chip-outline cube-outline albums-outline layers-outline globe-outline
lock-closed-outline flash-outline ellipse help-circle-outline arrow-forward pause-circle-outline power-outline
information-circle-outline swap-vertical-outline bug-outline shield-half-outline cloud-upload-outline
share-outline chevron-up archive-outline construct-outline lock-open-outline play-outline git-pull-request-outline
ribbon-outline close-circle-outline stop-circle-outline resize-outline`.split(/\s+/);

const available = new Set([...readFileSync(join(root, 'node_modules/ionicons/icons/index.d.ts'), 'utf8').matchAll(/export declare var (\w+)/g)].map((m) => m[1]));
const camel = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const names = [...new Set([...fromAgent, ...ui].map(camel))].sort();
const missing = names.filter((n) => !available.has(n));
if (missing.length) {
  console.error(`Not in ionicons: ${missing.join(', ')}`);
  process.exit(1);
}
const list = (indent) => names.map((n) => `${indent}${n},`).join('\n');
writeFileSync(
  join(root, 'src/app/core/icons.ts'),
  `// Generated by scripts/generate-icons.mjs. Do not edit by hand.
import { addIcons } from 'ionicons';
import {
${list('  ')}
} from 'ionicons/icons';

/**
 * Every ionicon the app uses, registered once at start. The agent names icons
 * of components it recognises (agent/src/discovery/catalog.ts): those are here
 * too, so a newly recognised component never shows a blank slot.
 */
export function registerIcons(): void {
  addIcons({
${list('    ')}
  });
}
`,
);
console.log(`${names.length} icons`);
